/**
 * The endpoint of a model, `null` when the model does not support it.
 * @param {string | undefined} modelCode e.g. "X102VE" (vehicle details `model.code`)
 * @param {string} key e.g. "battery-status", "actions/charge-start"
 * @returns {{ path: string, mode: string } | null}
 */
export function endpointFor(modelCode, key) {
  const model = modelCode ? VEHICLE_ENDPOINTS[modelCode] : undefined;
  if (model && Object.hasOwn(model, key)) return model[key];
  return DEFAULT_ENDPOINTS[key] ?? null;
}

/** Whether the model is documented in the table (an unknown one uses the defaults). */
export const isKnownModel = (modelCode) => Boolean(modelCode && VEHICLE_ENDPOINTS[modelCode]);
